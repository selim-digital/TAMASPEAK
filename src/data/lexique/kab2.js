/**
 * DICTIONNAIRE ÉTENDU — KABYLE (taqbaylit). Deuxième lot.
 *
 * Même règle que le premier (voir kab.js) : ces mots ne sont enseignés par
 * aucune leçon, la fiche le dit, et ils sont là pour qu'on y pioche en
 * écrivant les unités suivantes.
 *
 * CE QUI CHANGE AVEC CE LOT : il a été relu contre une source, mot par mot.
 * Chaque entrée a été cherchée dans le texte du « Dictionnaire kabyle-
 * français » de J.-M. Dallet (SELAF, 1982), et n'est restée que si le Dallet
 * donne cette forme avec ce sens. Une liste de départ d'environ 600 mots en
 * a perdu une quarantaine, introuvables, et une cinquantaine ont été
 * corrigés : la forme kabyle à la place d'une forme marocaine (« ticcert »,
 * l'ail, et non « tiskert »), ou le sens que donne vraiment le dictionnaire
 * (« bururu » est la chouette, pas le hibou).
 *
 * DEUX EXCEPTIONS, signalées dans leur note : « tayri » et « tilelli », mots
 * de l'usage moderne que le Dallet n'a pas. Et les EXPRESSIONS, à la fin, ne
 * sont pas des entrées de dictionnaire : seuls leurs mots ont été vérifiés.
 *
 * CE N'EST PAS UNE VALIDATION PAR UN LOCUTEUR. Le Dallet décrit le parler des
 * At Mangellat au milieu du XXᵉ siècle : un mot peut avoir vieilli, ou se
 * dire autrement à Béjaïa. La relecture a été faite sur le texte numérisé
 * (archive.org), dont la reconnaissance des caractères abîme les lettres
 * pointées — une emphatique (ṭ, ḍ, ẓ…) peut donc être mal placée. La
 * relecture par un locuteur natif reste due, comme pour tout le contenu.
 *
 * Toujours pas de pluriels devinés, pas d'état d'annexion, pas de
 * conjugaison (verbes à l'impératif) — et ni musique ni danse.
 */

